def printable_ranges() -> list[tuple[int, int]]:
    """The inclusive ranges of Unicode scalar values ``str.isprintable()`` accepts."""
    found: list[tuple[int, int]] = []
    start = previous = None
    for code in range(0x110000):
        if code in SURROGATES or not chr(code).isprintable():
            continue
        if start is None or previous != code - 1:
            if start is not None:
                found.append((start, previous))
            start = code
        previous = code
    if start is not None:
        found.append((start, previous))
    return found


def commented(text: str) -> list[str]:
    """``text`` as the lines of a Rust module comment."""
    return [f"//! {line}" if line else "//!" for line in text.splitlines()]


def main() -> None:
    python = sys.version.split()[0]
    header = (
        "The characters Python's `str.isprintable()` accepts, which its `repr` of a\n"
        "`str` writes as they are. Generated by\n"
        "`scripts/generate_printable_ranges.py` from the Unicode "
        f"{unicodedata.unidata_version} data of\n"
        f"Python {python}. Do not edit; run the script again.\n"
        "\n"
        "The data is derived from Unicode data files, under this notice:\n"
        "\n"
    )
    items = [f"('\\u{{{start:x}}}', '\\u{{{end:x}}}')," for start, end in printable_ranges()]
    lines = commented(header + UNICODE_NOTICE)
    lines += [
        "",
        "/// Inclusive ranges, sorted.",
        "#[rustfmt::skip]",
        "pub(super) static PRINTABLE: &[(char, char)] = &[",
    ]
    lines += [
        "    " + " ".join(items[at : at + PER_LINE]) for at in range(0, len(items), PER_LINE)
    ]
    lines.append("];")
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    LICENSE.write_text(UNICODE_NOTICE, encoding="utf-8")
    print(
        f"Wrote {TABLE.relative_to(REPOSITORY)}: {len(items)} ranges, "
        f"Unicode {unicodedata.unidata_version}, Python {python}"
    )
    print(f"Wrote {LICENSE.relative_to(REPOSITORY)}")


if __name__ == "__main__":
    main()
